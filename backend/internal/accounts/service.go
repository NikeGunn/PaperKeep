// Login (1A.11)
// -------------------------------------------------------------------------

// Login authenticates a user with constant-time behaviour whether the account
// exists or not (prevents user-enumeration via timing).
func (s *Service) Login(ctx context.Context, req LoginRequest) (*LoginResponse, error) {
	account, err := s.q.GetAccountByEmail(ctx, req.Email)
	if err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			// User does not exist — run dummy Argon2id to prevent timing leak
			auth.DummyVerify()
			return nil, ErrBadCredentials
		}
		return nil, fmt.Errorf("fetching account: %w", err)
	}

	// Verify password (constant-time)
	ok, err := auth.VerifyPassword(req.AuthHash, account.AuthHash)
	if err != nil {
		return nil, fmt.Errorf("verifying password: %w", err)
	}
	if !ok {
		return nil, ErrBadCredentials
	}

	// Check account status
	switch account.Status {
	case "suspended", "pending_deletion":
		return nil, ErrAccountSuspended
	}

	// Require email verification
	if !account.EmailVerified {
		return nil, ErrUnverified
	}

	// Mint access token
	uuidStr, err := uuidToString(account.Uuid)
	if err != nil {
		return nil, err
	}
	accessToken, err := s.maker.MakeAccessToken(auth.Claims{
		AccountID:   account.ID,
		AccountUUID: uuidStr,
		Email:       account.Email,
	})
	if err != nil {
		return nil, fmt.Errorf("minting access token: %w", err)
	}

	// Generate refresh token
	rawRefresh, refreshHash, err := auth.GenerateRefreshToken()
	if err != nil {
		return nil, fmt.Errorf("generating refresh token: %w", err)
	}

	expiresAt := pgtype.Timestamptz{Time: time.Now().Add(auth.RefreshTokenTTL), Valid: true}
	_, err = s.q.CreateRefreshToken(ctx, db.CreateRefreshTokenParams{
		AccountID:   account.ID,
		TokenHash:   refreshHash,
		DeviceLabel: nil,
		ExpiresAt:   expiresAt,
	})
	if err != nil {
		return nil, fmt.Errorf("storing refresh token: %w", err)
	}

	return &LoginResponse{
		AccessToken:  accessToken,
		RefreshToken: rawRefresh,
		WrappedKey:   encodeBase64(account.WrappedKey),
		KDFSalt:      encodeBase64(account.KdfSalt),
		KDFParams:    account.KdfParams.String,
	}, nil
}

// -------------------------------------------------------------------------
// Refresh (1A.12)
// -------------------------------------------------------------------------

// RefreshSession validates the refresh token, rotates it, and returns a new pair.
// Replay detection: if a revoked token is presented, ALL account tokens are revoked.
func (s *Service) RefreshSession(ctx context.Context, req RefreshRequest) (*RefreshResponse, error) {
	hash := auth.HashRefreshToken(req.RefreshToken)

	row, err := s.q.GetRefreshTokenByHash(ctx, hash)
	if err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			return nil, ErrBadCredentials
		}
		return nil, fmt.Errorf("fetching refresh token: %w", err)
	}

	// Replay detection: revoked token presented → revoke ALL for account
	if row.RevokedAt.Valid {
		s.logger.Warn("replay attack detected — revoking all sessions",
			slog.Int64("account_id", row.AccountID))
		if rErr := s.q.RevokeAllRefreshTokensForAccount(ctx, row.AccountID); rErr != nil {
			s.logger.Error("failed to revoke all tokens", slog.String("error", rErr.Error()))
		}
		return nil, ErrRefreshRevoked
	}

	// Check expiry
	if time.Now().After(row.ExpiresAt.Time) {
		return nil, ErrRefreshExpired
	}

	// Load account for token claims
	account, err := s.q.GetAccountByID(ctx, row.AccountID)
	if err != nil {
		return nil, fmt.Errorf("fetching account: %w", err)
	}

	if account.Status != "active" {
		return nil, ErrAccountSuspended
	}

	// Revoke the old token
	if err := s.q.RevokeRefreshToken(ctx, row.ID); err != nil {
		return nil, fmt.Errorf("revoking old token: %w", err)
	}

	// Mint new access token
	uuidStr, err := uuidToString(account.Uuid)
	if err != nil {
		return nil, err
	}
	accessToken, err := s.maker.MakeAccessToken(auth.Claims{
		AccountID:   account.ID,
		AccountUUID: uuidStr,
		Email:       account.Email,
	})
	if err != nil {
		return nil, fmt.Errorf("minting access token: %w", err)
	}

	// Generate new refresh token
	rawRefresh, refreshHash, err := auth.GenerateRefreshToken()
	if err != nil {
		return nil, fmt.Errorf("generating refresh token: %w", err)
	}

	expiresAt := pgtype.Timestamptz{Time: time.Now().Add(auth.RefreshTokenTTL), Valid: true}
	_, err = s.q.CreateRefreshToken(ctx, db.CreateRefreshTokenParams{
		AccountID:   account.ID,
		TokenHash:   refreshHash,
		DeviceLabel: row.DeviceLabel,
		ExpiresAt:   expiresAt,
	})
	if err != nil {
		return nil, fmt.Errorf("storing new refresh token: %w", err)
	}

	return &RefreshResponse{
		AccessToken:  accessToken,
		RefreshToken: rawRefresh,
	}, nil
}

// -------------------------------------------------------------------------
// Helpers
// -------------------------------------------------------------------------

func validateEmail(email string) error {
	if len(email) > 254 {
		return errors.New("email too long")
	}
	_, err := mail.ParseAddress(email)
	return err
}

func isUniqueViolation(err error) bool {
	return err != nil && (contains(err.Error(), "23505") || contains(err.Error(), "unique"))
}

func contains(s, sub string) bool {
	return len(s) >= len(sub) && (s == sub || len(s) > 0 && containsStr(s, sub))
}

func containsStr(s, sub string) bool {
	for i := 0; i <= len(s)-len(sub); i++ {
		if s[i:i+len(sub)] == sub {
			return true
		}
	}
	return false
}

func uuidToString(u pgtype.UUID) (string, error) {
	if !u.Valid {
		return "", errors.New("invalid UUID")
	}
	b := u.Bytes
	return fmt.Sprintf("%08x-%04x-%04x-%04x-%012x",
		b[0:4], b[4:6], b[6:8], b[8:10], b[10:16]), nil
}

func hashToken(raw string) []byte {
	sum := sha256.Sum256([]byte(raw))
	return sum[:]
}

func encodeBase64(b []byte) string {
	return fmt.Sprintf("%x", b)
}
